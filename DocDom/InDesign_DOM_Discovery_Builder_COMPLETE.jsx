/**
 * Simple object stringification for ES3 compatibility
 * @param {*} obj - Object to stringify
 * @param {Number} depth - Current depth
 * @returns {String} - JSON-like string
 */
function stringifyObject(obj, depth) {
    // Simple implementation - could be enhanced
    if (depth > 3) return '"[max depth]"';
    
    if (obj === null) return 'null';
    if (obj === undefined) return 'undefined';
    
    var type = typeof obj;
    
    if (type === 'string') return '"' + obj.replace(/"/g, '\\"') + '"';
    if (type === 'number' || type === 'boolean') return String(obj);
    
    if (type === 'object') {
        if (obj.constructor === Array || (obj.length !== undefined && typeof obj.length === 'number')) {
            // Handle arrays
            var parts = ['['];
            var arrayLength = obj.length || 0;
            for (var i = 0; i < Math.min(arrayLength, 10); i++) {  // Limit array size
                if (i > 0) parts.push(',');
                parts.push(stringifyObject(obj[i], depth + 1));
            }
            if (arrayLength > 10) parts.push(',"[...more items]"');
            parts.push(']');
            return parts.join('');
        } else {
            // Handle objects
            var parts = ['{'];
            var first = true;
            var count = 0;
            for (var key in obj) {
                if (count >= 20) {  // Limit object properties
                    if (!first) parts.push(',');
                    parts.push('"[...more properties]":"truncated"');
                    break;
                }
                if (!first) parts.push(',');
                parts.push('"' + key + '":');
                parts.push(stringifyObject(obj[key], depth + 1));
                first = false;
                count++;
            }
            parts.push('}');
            return parts.join('');
        }
    }
    
    return '"[' + type + ']"';
}

